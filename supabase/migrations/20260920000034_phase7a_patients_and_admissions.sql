-- ---------------------------------------------------------------------------
-- 5. save_admission() - find-or-create, so a returning IPD patient is one episode
--
--    The IPD details step has an admission number and, on a new admission, the date,
--    ward, bed and treating doctor. Rather than making the screen check-then-insert
--    (which races with itself on a double-submit), this does both in one transaction:
--    the number already names an episode for this patient, so it returns that row;
--    otherwise it creates one.
--
--    It fills a descriptive field only where the stored row has none. That is a
--    deliberate exception to "do not edit an existing record" and it is bounded: an
--    admission number that arrives with a ward this episode did not have is new
--    information about the same episode, and dropping it would lose what the operator
--    typed. Nothing about money, the patient, or the doctor link is ever rewritten.
-- ---------------------------------------------------------------------------
create or replace function public.save_admission(
  p_customer_id uuid,
  p_admission_no text,
  p_hospital_id uuid default null,
  p_admitted_on date default null,
  p_ward text default null,
  p_bed text default null,
  p_doctor_id uuid default null,
  p_doctor_name text default null,
  p_notes text default null
) returns public.admissions
language plpgsql
security definer
set search_path = public
as $$
declare
  v_pharmacy   uuid := public.get_my_pharmacy_id();
  v_no         text := btrim(coalesce(p_admission_no, ''));
  v_hospital   uuid := p_hospital_id;
  v_doctor     uuid := p_doctor_id;
  v_doctor_nm  text := nullif(btrim(coalesce(p_doctor_name, '')), '');
  v_admission  public.admissions;
begin
  if v_pharmacy is null then
    raise exception 'no pharmacy scope for the signed-in user'
      using errcode = 'insufficient_privilege';
  end if;

  if v_no = '' then
    raise exception 'an admission needs the hospital''s IPD or OPD number'
      using errcode = 'check_violation';
  end if;

  if not exists (
    select 1 from public.customers c
     where c.id = p_customer_id and c.pharmacy_id = v_pharmacy
  ) then
    raise exception 'that patient is not in this pharmacy'
      using errcode = 'check_violation';
  end if;

  -- No hospital given: take the pharmacy's own, which is the prefill D-067 asks for.
  if v_hospital is null then
    select p.hospital_id into v_hospital
      from public.pharmacies p
     where p.id = v_pharmacy;
  end if;

  if v_hospital is not null and not exists (
    select 1 from public.hospitals h
     where h.id = v_hospital and h.pharmacy_id = v_pharmacy
  ) then
    raise exception 'that hospital is not in this pharmacy'
      using errcode = 'check_violation';
  end if;

  if v_doctor is not null then
    select d.name into v_doctor_nm
      from public.doctors d
     where d.id = v_doctor and d.pharmacy_id = v_pharmacy;

    if not found then
      raise exception 'that doctor is not in this pharmacy'
        using errcode = 'check_violation';
    end if;
  elsif v_doctor_nm is not null then
    -- A name with no master row: match it case-insensitively, and create the master
    -- only when nothing matches, so a repeated prescriber converges on one row (D-072).
    select d.id into v_doctor
      from public.doctors d
     where d.pharmacy_id = v_pharmacy
       and lower(d.name) = lower(v_doctor_nm);

    if v_doctor is null then
      insert into public.doctors (pharmacy_id, name)
      values (v_pharmacy, v_doctor_nm)
      returning id into v_doctor;
    end if;
  end if;

  select * into v_admission
    from public.admissions a
   where a.pharmacy_id = v_pharmacy
     and a.customer_id = p_customer_id
     and a.admission_no = v_no;

  if found then
    update public.admissions a
       set ward                 = coalesce(a.ward, nullif(btrim(coalesce(p_ward, '')), '')),
           bed                  = coalesce(a.bed, nullif(btrim(coalesce(p_bed, '')), '')),
           hospital_id          = coalesce(a.hospital_id, v_hospital),
           treating_doctor_id   = coalesce(a.treating_doctor_id, v_doctor),
           treating_doctor_name = coalesce(a.treating_doctor_name, v_doctor_nm),
           notes                = coalesce(a.notes, nullif(btrim(coalesce(p_notes, '')), ''))
     where a.id = v_admission.id
    returning * into v_admission;

    return v_admission;
  end if;

  insert into public.admissions (
    pharmacy_id, customer_id, hospital_id, admission_no, admitted_on,
    ward, bed, treating_doctor_id, treating_doctor_name, notes, status
  ) values (
    v_pharmacy,
    p_customer_id,
    v_hospital,
    v_no,
    coalesce(p_admitted_on, current_date),
    nullif(btrim(coalesce(p_ward, '')), ''),
    nullif(btrim(coalesce(p_bed, '')), ''),
    v_doctor,
    v_doctor_nm,
    nullif(btrim(coalesce(p_notes, '')), ''),
    'active'
  )
  returning * into v_admission;

  return v_admission;
end;
$$;

