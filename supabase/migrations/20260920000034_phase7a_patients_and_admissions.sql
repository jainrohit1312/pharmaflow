-- ---------------------------------------------------------------------------
-- 3. normalize_indian_mobile() - one canonical form for every mobile we store or match
--
--    The brief: "Normalize Indian mobile input consistently; accept +91 formatting and
--    store canonical form." Returns NULL for anything that is not a 10-digit Indian
--    mobile (starting 6-9) rather than raising, because it is used in two places with
--    two different needs: a write path that must refuse a bad number with its own
--    wording, and a search path where a nonsense term simply matches no phone. A
--    landline is deliberately not accepted as a mobile - the details step requires a
--    mobile, and silently storing "011-2345" as one would make the lookup useless.
-- ---------------------------------------------------------------------------
create or replace function public.normalize_indian_mobile(p_text text)
returns text
language sql
immutable
set search_path = public
as $$
  select case
    when p_text is null then null
    else (
      with digits as (
        select regexp_replace(p_text, '[^0-9]', '', 'g') as d
      ), trimmed as (
        select case
          when length(d) = 12 and left(d, 2) = '91' then right(d, 10)
          when length(d) = 11 and left(d, 1) = '0'  then right(d, 10)
          else d
        end as d
        from digits
      )
      select case
        when length(d) = 10 and left(d, 1) ~ '[6-9]' then d
        else null
      end
      from trimmed
    )
  end;
$$;

comment on function public.normalize_indian_mobile(text) is
  'Canonical 10-digit Indian mobile (strips +91, spaces, dashes and a leading zero; 6-9 leading digit), or NULL when the text is not a mobile number.';

