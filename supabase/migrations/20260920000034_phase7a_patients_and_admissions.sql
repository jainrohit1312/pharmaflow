-- What this file decides, because D-067 left it open
-- -------------------------------------------------
-- D-067 recorded the open question in its own words: "A counter patient is not
-- necessarily a customer row, so Phase 7 decides whether a counter sale finds-or-
-- creates a customer, or stays denormalised on the sale." **This file answers it: the
-- patient IS a `customers` row.** The owner's brief says so - "Use the existing
-- customers identity where compatible; do not create a competing patient master
-- without demonstrating why it is necessary" - and nothing here demonstrates a reason
-- for a second identity table. So `customers` gains the fields a patient needs (a
-- generated code, the demographics the details step asks for) and the sale keeps its
-- own `patient_name` / `patient_mobile` snapshot (D-067) so that editing a patient
-- later cannot rewrite an old bill.
--
-- Admission is a different thing from patient, and the brief says why: one patient
-- has many admissions over time. `admissions` is therefore its own table, linked to
-- the patient (`customer_id`) and to the hospital, and it carries the hospital's own
-- IPD number. That number is D-067's `hospital_reference`: the *external* reference.
-- It is not the patient's id and it is not a UUID - D-067 already resolved that
-- ("It is one column - hospital_reference, the OPD/IPD number - and patient_id is not
-- a column"), and this file keeps the two identities apart: `customers.id` /
-- `customers.patient_code` name the patient, `admissions.admission_no` names the
-- episode at the hospital.
--
-- The money is NOT computed here. This file creates the identity and the episode; the
-- charges, returns, allocations and balances that make an admission's outstanding a
-- server-derived figure live in 00035, next to the sale write path that creates them.

