-- ---------------------------------------------------------------------------
-- 6. save_patient() - find-or-create a patient, and never edit an existing one
--
--    Three behaviours worth naming, because each is a rule from the brief:
--
--      * p_patient_id given  - the operator picked a returning patient. The row is
--        checked for tenancy and returned UNCHANGED. Details typed on a bill do not
--        silently edit the master ("invoice-specific details must not silently edit
--        the master"), so the only write is a missing patient_code, which is identity
--        rather than invoice detail.
--      * nothing matches      - a new patient is registered with a generated code.
--      * the same submission twice - a retry is not a second patient. When the same
--        name and the same canonical mobile were registered by this pharmacy in the
--        last ten minutes, that row is returned instead of a duplicate. That is a
--        double-submit guard, NOT a merge: a genuinely different patient with the same
--        name and a shared family mobile is a deliberate second registration, which is
--        why the window is minutes and why the caller is shown candidates first
--        (`search_patients`) rather than being deduplicated behind its back.
--
--    Contact rule: a patient's own mobile, or a guardian's for a child or dependant
--    ("a guardian's mobile satisfies the contact requirement"). At least one of the two
--    is required; a patient with neither is refused rather than invented.
-- ---------------------------------------------------------------------------
create or replace function public.save_patient(
  p_name text,
  p_mobile text default null,
  p_patient_id uuid default null,
  p_address text default null,
  p_date_of_birth date default null,
  p_age_years int default null,
  p_age_months int default null,
  p_sex text default null,
  p_guardian_name text default null,
  p_guardian_phone text default null,
  p_notes text default null
) returns public.customers
language plpgsql
security definer
set search_path = public
as $$
declare
  v_pharmacy   uuid := public.get_my_pharmacy_id();
  v_name       text := btrim(coalesce(p_name, ''));
  v_mobile     text := public.normalize_indian_mobile(p_mobile);
  v_guardian   text := public.normalize_indian_mobile(p_guardian_phone);
  v_sex        text := nullif(lower(btrim(coalesce(p_sex, ''))), '');
  v_patient    public.customers;
begin
  if v_pharmacy is null then
    raise exception 'no pharmacy scope for the signed-in user'
      using errcode = 'insufficient_privilege';
  end if;

  if v_name = '' then
    raise exception 'a patient needs a name'
      using errcode = 'check_violation';
  end if;

  -- A returning patient: checked, returned as-is, and given a code if it predates 7a.
  if p_patient_id is not null then
    select * into v_patient
      from public.customers c
     where c.id = p_patient_id
       and c.pharmacy_id = v_pharmacy;

    if not found then
      raise exception 'that patient is not in this pharmacy'
        using errcode = 'check_violation';
    end if;

    if v_patient.patient_code is null then
      update public.customers c
         set patient_code = public.next_patient_code()
       where c.id = v_patient.id
      returning * into v_patient;
    end if;

    return v_patient;
  end if;

  if p_mobile is not null and btrim(p_mobile) <> '' and v_mobile is null then
    raise exception 'that mobile number is not a valid Indian mobile (10 digits, starting 6-9)'
      using errcode = 'check_violation';
  end if;

  if p_guardian_phone is not null and btrim(p_guardian_phone) <> '' and v_guardian is null then
    raise exception 'that guardian mobile number is not a valid Indian mobile (10 digits, starting 6-9)'
      using errcode = 'check_violation';
  end if;

  if v_mobile is null and v_guardian is null then
    raise exception 'a patient needs a mobile number, or a guardian''s for a child or dependant'
      using errcode = 'check_violation';
  end if;

  if v_sex is not null and v_sex not in ('male', 'female', 'other') then
    raise exception 'sex must be male, female or other'
      using errcode = 'check_violation';
  end if;

  if p_date_of_birth is not null and p_date_of_birth > current_date then
    raise exception 'a date of birth cannot be in the future'
      using errcode = 'check_violation';
  end if;

  -- Double-submit guard. Scoped to this pharmacy and to the last ten minutes; see the
  -- header for why this is not a deduplicate-by-name rule.
  select * into v_patient
    from public.customers c
   where c.pharmacy_id = v_pharmacy
     and lower(btrim(c.name)) = lower(v_name)
     and coalesce(c.phone, '') = coalesce(v_mobile, v_guardian, '')
     and c.created_at > now() - interval '10 minutes'
   order by c.created_at desc
   limit 1;

  if found then
    return v_patient;
  end if;

  insert into public.customers (
    pharmacy_id, name, phone, address, patient_code,
    date_of_birth, age_years, age_months, sex,
    guardian_name, guardian_phone, notes
  ) values (
    v_pharmacy,
    v_name,
    -- The patient's own number when there is one, otherwise the guardian's, so the
    -- family is findable by the number they actually gave.
    coalesce(v_mobile, v_guardian),
    nullif(btrim(coalesce(p_address, '')), ''),
    public.next_patient_code(),
    p_date_of_birth,
    p_age_years,
    p_age_months,
    v_sex,
    nullif(btrim(coalesce(p_guardian_name, '')), ''),
    v_guardian,
    nullif(btrim(coalesce(p_notes, '')), '')
  )
  returning * into v_patient;

  return v_patient;
end;
$$;

