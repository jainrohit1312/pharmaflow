-- ---------------------------------------------------------------------------
-- 7. search_patients() - the returning-patient lookup
--
--    Matches the three things the brief names: the canonical mobile, the patient code
--    (prefix) and the name (case-insensitive, anywhere). `normalize_indian_mobile` is
--    applied to the STORED value as well as the term, so a number saved before Phase 7a
--    in "+91 98…" form is still found - a concession to existing rows, paid for with a
--    function call per row on a table of this size rather than a bulk rewrite of data
--    the phase is not allowed to touch.
--
--    `active_admission_count` is on the result because the details step has to know
--    whether to ask which admission (a patient with two open episodes must choose).
-- ---------------------------------------------------------------------------
create or replace function public.search_patients(
  p_term text default null,
  p_limit int default 20,
  p_offset int default 0
) returns table (
  id uuid,
  name text,
  patient_code text,
  phone text,
  address text,
  date_of_birth date,
  age_years int,
  age_months int,
  sex text,
  guardian_name text,
  guardian_phone text,
  notes text,
  is_active boolean,
  active_admission_count int
)
language sql
stable
security definer
set search_path = public
as $$
  with scoped as (
    select
      c.*,
      public.normalize_indian_mobile(p_term)                          as term_mobile,
      btrim(coalesce(p_term, ''))                                     as term_text,
      (select count(*)::int
         from public.admissions a
        where a.customer_id = c.id
          and a.pharmacy_id = c.pharmacy_id
          and a.status = 'active')                                    as open_admissions
      from public.customers c
     where c.pharmacy_id = public.get_my_pharmacy_id()
  )
  select
    s.id,
    s.name,
    s.patient_code,
    s.phone,
    s.address,
    s.date_of_birth,
    s.age_years,
    s.age_months,
    s.sex,
    s.guardian_name,
    s.guardian_phone,
    s.notes,
    s.is_active,
    s.open_admissions
  from scoped s
  where s.term_text = ''
     or (s.term_mobile is not null
         and (s.phone = s.term_mobile
              or public.normalize_indian_mobile(s.phone) = s.term_mobile))
     or (s.patient_code is not null and s.patient_code ilike s.term_text || '%')
     or s.name ilike '%' || s.term_text || '%'
  order by
    case
      when s.term_mobile is not null
       and (s.phone = s.term_mobile
            or public.normalize_indian_mobile(s.phone) = s.term_mobile) then 0
      when s.patient_code ilike s.term_text || '%' then 1
      else 2
    end,
    s.name
  limit least(greatest(coalesce(p_limit, 20), 1), 50)
  offset greatest(coalesce(p_offset, 0), 0);
$$;

comment on function public.search_patients(text, integer, integer) is
  'Patient lookup by canonical mobile, patient-code prefix or case-insensitive name, tenant-scoped and paginated (max 50 rows). Read-only; an empty term lists the pharmacy''s patients.';

-- ---------------------------------------------------------------------------
-- 8. patient_admissions() - the episodes offered when a patient has several
-- ---------------------------------------------------------------------------
create or replace function public.patient_admissions(p_customer_id uuid)
returns table (
  id uuid,
  admission_no text,
  hospital_id uuid,
  hospital_name text,
  admitted_on date,
  discharged_on date,
  ward text,
  bed text,
  treating_doctor_name text,
  status text,
  created_at timestamptz
)
language sql
stable
security definer
set search_path = public
as $$
  select
    a.id,
    a.admission_no,
    a.hospital_id,
    h.name,
    a.admitted_on,
    a.discharged_on,
    a.ward,
    a.bed,
    a.treating_doctor_name,
    a.status,
    a.created_at
  from public.admissions a
  left join public.hospitals h on h.id = a.hospital_id
  where a.pharmacy_id = public.get_my_pharmacy_id()
    and a.customer_id = p_customer_id
  order by
    -- Open episodes first, then most recent: the one being billed is almost always an
    -- active one, and a patient's history is wanted newest-first.
    case when a.status = 'active' then 0 else 1 end,
    a.admitted_on desc,
    a.created_at desc;
$$;

comment on function public.patient_admissions(uuid) is
  'Every admission of one patient, active first. Tenant-scoped; the details step uses it to require an explicit choice when a patient has more than one open episode.';

-- ---------------------------------------------------------------------------
-- 9. Grants - the same convention as every other RPC in this tree
--
--    The code minter and the normaliser are reachable only from the definer functions
--    that gate on the tenant first, so they are revoked from every role (the same
--    treatment opening_stock_classify gets in 00031).
-- ---------------------------------------------------------------------------
do $$
begin
  execute 'grant execute on function public.save_patient(text, text, uuid, text, date, integer, integer, text, text, text, text) to authenticated';
  execute 'revoke execute on function public.save_patient(text, text, uuid, text, date, integer, integer, text, text, text, text) from anon, public';

  execute 'grant execute on function public.save_admission(uuid, text, uuid, date, text, text, uuid, text, text) to authenticated';
  execute 'revoke execute on function public.save_admission(uuid, text, uuid, date, text, text, uuid, text, text) from anon, public';

  execute 'grant execute on function public.search_patients(text, integer, integer) to authenticated';
  execute 'revoke execute on function public.search_patients(text, integer, integer) from anon, public';

  execute 'grant execute on function public.patient_admissions(uuid) to authenticated';
  execute 'revoke execute on function public.patient_admissions(uuid) from anon, public';

  execute 'revoke execute on function public.next_patient_code() from anon, authenticated, public';
  execute 'revoke execute on function public.normalize_indian_mobile(text) from anon, authenticated, public';
exception
  when undefined_object then
    -- Role or function missing in a bare (non-Supabase) cluster: nothing to grant.
    null;
end $$;
